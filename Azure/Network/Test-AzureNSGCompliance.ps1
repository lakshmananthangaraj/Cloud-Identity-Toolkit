                        schema.
    1.0 (29-Jul-2026) - Initial release.

    ─────────────────────────────────────────────────────────────────────────
    Pre-Requisites:
    ─────────────────────────────────────────────────────────────────────────
    1. A CSV produced by Get-AzureNSGInventory.ps1 v1.2 or later (earlier
       versions do not emit the merged SourceAddressAll/SourcePortAll/
       DestinationAddressAll/DestinationPortAll columns this function relies
       on for the exposure checks).
    2. PowerShell 5.1 or later.
    3. Only if -IncludeFlowLogCheck is used: Az.Accounts and Az.Network
       modules, plus Reader access on the target subscriptions' Network
       Watcher resources. Not required for the default offline analysis.

    ─────────────────────────────────────────────────────────────────────────
    Execution Flow:
    ─────────────────────────────────────────────────────────────────────────
    1. Validate -CsvPath exists and, once imported, contains the columns this
       function depends on; error out with guidance if the schema looks like
       an older inventory version.
    2. If -IncludeFlowLogCheck: verify Az.Accounts/Az.Network are installed,
       verify/establish an authenticated session (same reuse-or-reauth prompt
       pattern as Get-AzureNSGInventory), then for every distinct subscription
       in the CSV, enumerate Network Watchers and their configured flow logs
       (both NSG-scoped and VNet-scoped) into an in-memory lookup table.
    3. Group the CSV rows by NSG. For each NSG: evaluate NSG-level findings
       (orphaned, unused, rule sprawl, missing flow logs), then evaluate
       Inbound and Outbound rule sets separately for rule-level findings
       (Any-Any, RDP/SSH/sensitive-port/wide-port Internet exposure, missing
       description, duplicate rules, and priority-conflict/shadowing).
       One subscription/NSG failing to parse does not abort the run.
    4. Risk-rate every finding and attach a general compliance reference.
    5. Export the detailed findings CSV and a per-NSG summary CSV (with a
       simple 0-100 compliance score) to -OutputPath. Optionally export a
       JSON summary. Optionally throw if -FailOnCritical and Critical
       findings exist, for CI/CD gating.

    ─────────────────────────────────────────────────────────────────────────
    Known Limitations:
    ─────────────────────────────────────────────────────────────────────────
    - Address/protocol scope comparisons (used for the Any-Any check and for
      priority-conflict/shadowing detection) are exact-string-or-wildcard
      only; this function does NOT perform CIDR subnet math. Two distinct,
      non-wildcard IP ranges that partially overlap (e.g. 10.0.0.0/16 vs.
      10.0.1.0/24) will not be detected as overlapping. Only exact matches or
      "*"/"Any"/"Internet" wildcards are treated as overlapping scopes.
    - Priority-conflict detection only considers Custom rules (Default rules
      are Azure-managed, always present, and not user-actionable).
    - The VNet Flow Log correlation (-IncludeFlowLogCheck) matches by virtual
      network NAME, parsed from the inventory's AssociatedSubnets column,
      because that column does not carry full VNet resource IDs. If two
      different VNets in the same subscription share the same name across
      resource groups, this heuristic can produce a false "flow logs found"
      match. Consider extending Get-AzureNSGInventory to also capture subnet/
      VNet resource IDs for a fully unambiguous correlation.
    - Port-range parsing supports single ports, comma-separated lists, and
      "start-end" ranges. Any other/unexpected port token format is skipped
      silently rather than guessed at.
    - ComplianceReference values point to the general CIS Azure Foundations
      Benchmark network-security domain and the Azure Security Benchmark "NS"
      control family. Exact control/section numbers vary by benchmark
      version, so map these to the specific version your organization has
      adopted rather than treating the text as an authoritative citation.
    - Wide-port-range, sensitive-port, and Any-Any findings can all fire for
      the same underlying rule; this is intentional (a single rule can
      violate more than one check) and is not de-duplicated.

