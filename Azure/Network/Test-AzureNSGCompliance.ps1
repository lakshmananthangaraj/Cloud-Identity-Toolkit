if ($MyInvocation.InvocationName -ne ".")
{
    Write-Host ""
    Write-Host "Function 'Test-AzureNSGCompliance' loaded. Usage examples:" -ForegroundColor DarkGray
    Write-Host "   Test-AzureNSGCompliance -CsvPath 'C:\Reports\NSG_Inventory_<timestamp>.csv'" -ForegroundColor White
    Write-Host "   Test-AzureNSGCompliance -CsvPath 'C:\Reports\NSG_Inventory_<timestamp>.csv' -IncludeFlowLogCheck -IncludeJsonExport" -ForegroundColor White
    Write-Host ""
}
