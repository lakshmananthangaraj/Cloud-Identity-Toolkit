.SYNOPSIS
    Offline Azure NSG Security & Compliance Gap Analysis Tool.
    Requirement 1 - Existing NSG Standardization and Compliance Assessment.
    Step 2: Analyze the baseline NSG inventory produced by Get-AzureNSGInventory
    for security risks, hygiene issues, and compliance gaps.

.DESCRIPTION
    Consumes the CSV produced by Get-AzureNSGInventory.ps1 (v1.2 or later) and
    runs a set of rule-level and NSG-level checks entirely offline, so re-running
    an analysis does not require re-querying Azure or holding an Azure session:
        - Any-Any (fully open) Allow rules, inbound and outbound
        - RDP (3389) and SSH (22) exposed directly to the Internet
        - Other sensitive management/service ports exposed to the Internet
          (WinRM, SMB, RPC, SQL/MySQL/PostgreSQL, Redis, MongoDB, VNC, etc.)
        - Wide destination port ranges exposed to the Internet
        - Priority conflicts (a rule shadowed/made unreachable by an earlier,
          conflicting-action rule with an overlapping scope)
        - Duplicate rules (different names, identical effective scope)
        - Rules missing a description
        - Orphaned NSGs (no subnet or NIC association)
        - Unused NSGs (no custom rules - relying entirely on Azure defaults)
        - NSG rule sprawl (custom rule count above a configurable threshold)

    Optionally (-IncludeFlowLogCheck), the function connects to Azure to check
    whether each NSG (or its associated virtual network) has flow logging
    enabled, covering both legacy NSG Flow Logs and the newer VNet Flow Logs.

    Findings are risk-rated (Critical/High/Medium/Low/Informational), mapped to
    a general compliance reference, and exported as a detailed CSV plus a
    per-NSG summary CSV. An optional JSON export supports downstream tooling
    or SIEM ingestion.

.PARAMETER CsvPath
    Mandatory. Path to the NSG inventory CSV generated by Get-AzureNSGInventory.ps1
    (v1.2 or later). Must exist and have a .csv extension.

.PARAMETER OutputPath
    Optional. Directory path where the findings/summary reports will be saved.
    Defaults to the current directory. Created automatically if it does not exist.

.PARAMETER ReportPrefix
    Optional. Prefix for the output report filenames. Default: "NSG_Compliance".
    Must not contain path separators or path-traversal sequences, since it is
    used to build output file names.

.PARAMETER WidePortRangeThreshold
    Optional. A destination port range wider than this many ports, exposed to
    the Internet, is flagged as a "wide port range" finding. Default: 100.

.PARAMETER RuleSprawlThreshold
    Optional. NSGs with more custom rules than this value are flagged as an
    informational "rule sprawl" finding. Default: 50.

.PARAMETER IncludeFlowLogCheck
    Optional switch. When specified, connects to Azure and checks Network
    Watcher flow log configuration (legacy NSG Flow Logs and VNet Flow Logs)
    for every NSG present in the CSV. Requires Az.Accounts and Az.Network and
    Reader access to Network Watcher resources in the target subscriptions.

.PARAMETER IncludeJsonExport
    Optional switch. When specified, also exports a JSON summary (finding
    counts by severity and category, plus per-NSG compliance scores)
    alongside the CSV reports.

.PARAMETER FailOnCritical
    Optional switch. When specified, throws a terminating error if any
    Critical-severity finding exists, after all reports have been exported.
    Intended for CI/CD pipeline gating - the caller decides how to act on it.

.INPUTS
    None. This function does not accept pipeline input.

.OUTPUTS
    None directly to the pipeline.

    Writes two CSV reports to disk (detailed findings + per-NSG summary), and
    optionally a JSON summary, that can be:
        - Opened directly in Excel for review and remediation tracking
        - Imported into Power BI
        - Used as the input dataset for a future
          Generate-AzureNSGComplianceDashboard.ps1

.EXAMPLE
    # Analyze a previously collected inventory CSV
    Test-AzureNSGCompliance -CsvPath "C:\Reports\NSG_Inventory_20260729_101500.csv"

.EXAMPLE
    # Analyze and also check flow log coverage against live Azure data
    Test-AzureNSGCompliance -CsvPath "C:\Reports\NSG_Inventory_20260729_101500.csv" -IncludeFlowLogCheck

.EXAMPLE
    # Custom thresholds, JSON export, and CI/CD gating on Critical findings
    Test-AzureNSGCompliance -CsvPath ".\NSG_Inventory_20260729_101500.csv" `
        -OutputPath "C:\Reports\Compliance" -ReportPrefix "Prod_NSG_Gaps" `
        -WidePortRangeThreshold 50 -RuleSprawlThreshold 30 `
        -IncludeJsonExport -FailOnCritical

.EXAMPLE
    # Full Requirement 1 pipeline

    Get-AzureNSGInventory -OutputPath "C:\Reports"

    Test-AzureNSGCompliance -CsvPath "C:\Reports\NSG_Inventory_<timestamp>.csv" `
        -OutputPath "C:\Reports" -IncludeFlowLogCheck -IncludeJsonExport

    Collects the Azure NSG inventory, then runs the offline + flow-log-aware
    compliance analysis against it, ready for Step 3 (dashboard visualization).

